    CUSTOMER_ID NUMBER
);

CREATE TABLE RP_PRODUCTS (
    PRODUCT_CODE VARCHAR2(10),
    PRODUCT_DESCRIPTION VARCHAR2(100),
    PRODUCT_CATEGORY VARCHAR2(50),
    COST_PRICE NUMBER
