    SALES_ID NUMBER,
    LAST_NAME VARCHAR2(100),
    FIRST_NAME VARCHAR2(100),
    STREET VARCHAR2(100),
    REP_CITY VARCHAR2(50),
    REP_STATE VARCHAR2(50),
    ZIP VARCHAR2(10),
    COMMISION NUMBER,
    RATE NUMBER
);

